// Staticlint — статический мультичекер (multichecker) для проекта
// yp-go-musthave-metrics.
//
// Он объединяет в одном исполняемом файле стандартные анализаторы Go,
// анализаторы проекта staticcheck.io, несколько сторонних анализаторов и
// один собственный. Мультичекер обходит исходный код указанных пакетов и
// сообщает о найденных проблемах — от вероятных багов до стилевых замечаний.
//
// # Запуск
//
// Каталог cmd/staticlint является самостоятельным Go-модулем, поэтому
// собирать анализатор нужно из его директории:
//
//	cd cmd/staticlint
//	go build -o staticlint .
//
// Запуск по всем пакетам проекта выполняется из корня репозитория:
//
//	./cmd/staticlint/staticlint ./...
//
// По умолчанию выполняются все анализаторы сразу. Чтобы запустить только
// некоторые из них, перечислите их флагами вида -<имя> — тогда сработают
// лишь указанные:
//
//	staticlint -printf -osexitchecker ./...
//
// Прочие возможности стандартного CLI, который предоставляет multichecker:
//
//	staticlint help            // вывести список всех анализаторов
//	staticlint help printf     // справка по конкретному анализатору
//	staticlint -json ./...     // вывод диагностик в формате JSON
//
// # Как устроена сборка набора
//
// Функция main формирует единый срез анализаторов suite и передаёт его в
// multichecker.Main, который и реализует разбор флагов, загрузку пакетов и
// запуск анализа. В suite попадают:
//
//   - фиксированный список стандартных passes (см. ниже);
//   - все анализаторы класса SA из honnef.co/go/tools/staticcheck
//     (добавляются в цикле по префиксу имени "SA");
//   - анализаторы класса S1 из honnef.co/go/tools/simple
//     (добавляются в цикле по префиксу имени "S1");
//   - анализатор ST1013 из honnef.co/go/tools/stylecheck;
//   - сторонние errcheck и bodyclose;
//   - собственный анализатор osexitchecker.
//
// # Стандартные анализаторы (golang.org/x/tools/go/analysis/passes)
//
//   - appends: append без добавляемых значений (append(s) без аргументов).
//   - asmdecl: несоответствия между ассемблерными файлами и объявлениями Go.
//   - assign: бесполезные присваивания (например, x = x).
//   - atomic: частые ошибки использования пакета sync/atomic.
//   - bools: ошибки с булевыми операторами (избыточные/противоречивые условия).
//   - buildtag: корректность директив //go:build и // +build.
//   - cgocall: нарушения правил передачи указателей в cgo.
//   - composites: композитные литералы без имён полей.
//   - copylocks: копирование по значению структур с sync-локами.
//   - defers: частые ошибки в defer (например, time.Since в defer вместо вызова).
//   - directive: директивы тулчейна Go, такие как //go:debug.
//   - errorsas: передача не-указателя или не-error вторым аргументом errors.As.
//   - framepointer: ассемблер, портящий frame pointer до его сохранения.
//   - httpresponse: ошибки работы с HTTP-ответами (defer Body.Close() до проверки err).
//   - hostport: корректность формата адреса host:port для net.Dial (в т.ч. IPv6).
//   - ifaceassert: невозможные приведения одного интерфейса к другому.
//   - loopclosure: захват переменной цикла во вложенных функциях/горутинах.
//   - lostcancel: cancel из context.WithCancel вызывается не на всех путях.
//   - nilfunc: бессмысленные сравнения функций с nil.
//   - nilness: избыточные или невозможные сравнения с nil и разыменования nil.
//   - printf: согласованность форматных строк Printf и переданных аргументов.
//   - scannererr: пропущенная проверка bufio.Scanner.Err.
//   - shift: сдвиги, равные или превышающие разрядность числа.
//   - sigchanyzer: небуферизированный канал os.Signal в signal.Notify.
//   - slog: некорректные вызовы структурного логирования log/slog.
//   - sortslice: неверный тип первого аргумента sort.Slice (не слайс).
//   - sqlrowserr: пропущенная проверка sql.Rows.Err после итерации.
//   - stdmethods: сигнатуры методов известных интерфейсов (String, Error и т.п.).
//   - stdversion: использование слишком новых символов stdlib для заявленной версии Go.
//   - stringintconv: подозрительные конверсии вида string(int).
//   - structtag: корректность тегов полей структур (reflect.StructTag.Get).
//   - tests: типичные ошибки в тестах и примерах.
//   - testinggoroutine: вызов (*testing.T).Fatal из горутины, запущенной тестом.
//   - timeformat: неверный опорный формат в time.Format/time.Parse (2006-02-01).
//   - unmarshal: передача не-указателя/не-интерфейса в функции Unmarshal.
//   - unreachable: недостижимый код.
//   - unsafeptr: некорректные конверсии uintptr в unsafe.Pointer.
//   - unusedresult: проигнорированный результат вызовов некоторых функций (fmt.Sprintf и др.).
//   - unusedwrite: записи в поля или элементы, которые далее нигде не читаются.
//   - waitgroup: неправильное использование sync.WaitGroup.
//
// # Анализаторы класса SA (honnef.co/go/tools/staticcheck)
//
// Подключается весь класс SA пакета staticcheck.io — это набор проверок на
// вероятные баги: некорректные регулярные выражения, гонки, ошибочные
// форматные строки, недостижимый или бессмысленный код, неверная работа со
// стандартной библиотекой и т.д. Анализаторы добавляются целиком по префиксу
// имени "SA".
//
// # Прочие классы staticcheck.io
//
//   - S1xxx (honnef.co/go/tools/simple): упрощение кода — конструкции, которые
//     можно записать короче и яснее (лишние if/else, циклы, конкатенации и т.п.).
//   - ST1013 (honnef.co/go/tools/stylecheck): использовать именованные константы
//     net/http вместо магических чисел HTTP-статусов.
//
// # Сторонние анализаторы
//
//   - errcheck (github.com/kisielk/errcheck): непроверенные возвращаемые ошибки.
//   - bodyclose (github.com/timakin/bodyclose): незакрытое тело HTTP-ответа
//     (resp.Body не закрывается через Close).
//
// # Собственный анализатор
//
//   - osexitchecker: запрещает прямой вызов os.Exit в функции main пакета main.
//     Вызов os.Exit определяется по типу (через go/types), поэтому проверка
//     устойчива к алиасам импорта и к одноимённым переменным; сгенерированные
//     тест-бинарники (.test) и код вне функции main не затрагиваются.
