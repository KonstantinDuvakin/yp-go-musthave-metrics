// Package pool предоставляет типобезопасную generic-обёртку над sync.Pool
// для переиспользования «тяжёлых» объектов.
//
// В отличие от sync.Pool, работающего с any, Pool[T] хранит объекты одного
// конкретного типа T и гарантирует, что перед возвратом в пул объект будет
// сброшен через его метод Reset(). Это защищает от утечки состояния между
// разными пользователями одного объекта.
package pool

import "sync"

// Resetter описывает объект, умеющий сбрасывать своё состояние в исходное.
//
// Метод Reset вызывается автоматически при возврате объекта в Pool через Put.
type Resetter interface {
	Reset()
}

// Pool — пул объектов типа T.
//
// Pool безопасен для одновременного использования из нескольких горутин.
// Как и sync.Pool, он не гарантирует, что положенный объект будет возвращён
// при следующем Get: сборщик мусора может освободить содержимое пула в любой
// момент. Поэтому Pool подходит только для кэширования, но не для хранения
// данных.
//
// Нулевое значение Pool непригодно к использованию — создавайте пул через New.
type Pool[T Resetter] struct {
	p sync.Pool
}

// New создаёт пул, который при отсутствии свободных объектов создаёт новые
// с помощью newFn.
//
// newFn должна возвращать готовый к использованию объект. Тип T выводится
// из её сигнатуры:
//
//	p := pool.New(func() *bytes.Buffer { return &bytes.Buffer{} })
func New[T Resetter](newFn func() T) *Pool[T] {
	return &Pool[T]{
		p: sync.Pool{
			New: func() any { return newFn() },
		},
	}
}

// Get возвращает объект из пула. Если свободных объектов нет, создаётся
// новый через фабрику, переданную в New.
//
// Полученный объект находится в сброшенном состоянии. После использования
// его следует вернуть в пул через Put.
func (p *Pool[T]) Get() T {
	return p.p.Get().(T)
}

// Put сбрасывает состояние obj вызовом Reset и помещает его в пул.
//
// После вызова Put обращаться к obj нельзя: он может быть выдан другой
// горутине.
func (p *Pool[T]) Put(obj T) {
	obj.Reset()
	p.p.Put(obj)
}
